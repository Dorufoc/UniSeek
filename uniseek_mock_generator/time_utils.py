# UniSeek 兼职招聘平台 - Mock 数据时间工具函数
# ==============================================================================
# 提供加权时间分布函数，使 Mock 数据在 2010-2026 年间均匀分布且近期密集，
# 以支持仪表盘趋势分析（近10年、近12个月、近30天、近7天、近24小时）。

import datetime
import random

# =============================================================================
# 时间段定义（带权重）
# =============================================================================
# 权重越高，该时间段内生成的数据点越多。
# 设计目标：
#   - 近10年（2016-2026）：各年份均有数据 ✅
#   - 近12个月（2025-07 至 2026-07）：约 45% 数据 ✅
#   - 近30天（2026-06 至 2026-07）：充足数据点 ✅
#   - 近7天（2026-07-18 至 2026-07-25）：每日活动 ✅
#   - 近24小时（2026-07-25）：小时级活动 ✅

TIME_SEGMENTS = [
    # (起始日期, 结束日期, 权重, 描述)
    # === 近10年趋势基础数据 ===
    
    # 2010-2015: 历史基线 - 6年，权重8 → ~1.33%/年
    ("2010-01-01", "2015-12-31", 8,    "2010-2015: 历史基线"),
    
    # 2016-2019: 增长期 - 4年，权重15 → ~3.75%/年
    ("2016-01-01", "2019-12-31", 15,   "2016-2019: 增长期"),
    
    # 2020-2024: 成熟期 - 5年，权重20 → 4%/年
    ("2020-01-01", "2024-12-31", 20,   "2020-2024: 成熟期"),
    
    # === 近期高密度数据：支撑各时间粒度看板 ===
    
    # 2025全年（1年），权重14
    ("2025-01-01", "2025-12-31", 14,   "2025年（近2年趋势）"),
    
    # 2026上半年（6个月），权重12 → 覆盖近12个月
    ("2026-01-01", "2026-06-30", 12,   "2026上半年（近12个月）"),
    
    # 2026年7月1-17日（17天），权重11 → 覆盖近30天
    ("2026-07-01", "2026-07-17", 11,   "近30天前半（每日粒度）"),
    
    # 2026年7月18-24日（7天），权重8 → 近7天前半
    ("2026-07-18", "2026-07-24", 8,    "近7天前半（每日粒度）"),
    
    # 2026年7月25-30日（6天），权重12 → 近一周，小时级粒度
    ("2026-07-25", "2026-07-30", 12,   "近一周（小时级）"),
]

# 缓存已解析的时间段
_PARSED = None


def _get_segments():
    """解析 TIME_SEGMENTS 中的日期字符串为 datetime 对象并缓存。"""
    global _PARSED
    if _PARSED is None:
        _PARSED = []
        for start_str, end_str, weight, desc in TIME_SEGMENTS:
            start = datetime.datetime.strptime(start_str, "%Y-%m-%d")
            # 结束时间取当天最后一秒
            end = (datetime.datetime.strptime(end_str, "%Y-%m-%d")
                   + datetime.timedelta(days=1)
                   - datetime.timedelta(seconds=1))
            _PARSED.append((start, end, weight, desc))
    return _PARSED


def weighted_random_time():
    """
     返回 2010-01-01 至 2026-07-25 之间的加权随机时间点。

    按时间段权重分布，确保近期数据更密集，支持各时间粒度的趋势分析。
    适合用于创建时间、日志时间等所有需要时间戳的字段。

    Returns:
        datetime.datetime: 加权随机时间点
    """
    segments = _get_segments()
    weights = [s[2] for s in segments]

    # 按权重随机选择一个时间段
    segment = random.choices(segments, weights=weights, k=1)[0]
    start, end, _, _ = segment

    # 在选中的时间段内均匀随机
    span = (end - start).total_seconds()
    offset = random.random() * span
    return start + datetime.timedelta(seconds=int(offset))
